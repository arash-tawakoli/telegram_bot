
create table if not exists public.cooperative_provider_registry (
  id bigint generated by default as identity primary key,
  provider_entity text not null unique,
  source_id smallint null references public.sources(id) on delete set null,
  aliases text[] not null default '{}',
  hamburg_only boolean not null default true,
  active boolean not null default true,
  registry_mode text not null default 'passive',
  notes text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.cooperative_provider_registry(
  provider_entity,source_id,aliases,hamburg_only,active,registry_mode,notes
)
select s.name,s.id,array[s.name]::text[],true,true,'source','Existing TraumWohnungHamburg cooperative source'
from public.sources s
where s.source_type='Baugenossenschaft'
on conflict(provider_entity) do update set
  source_id=excluded.source_id,
  active=true,
  registry_mode='source',
  updated_at=now();

