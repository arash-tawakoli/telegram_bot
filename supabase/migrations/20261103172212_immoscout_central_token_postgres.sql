SET lock_timeout = '2s';
SET statement_timeout = '30s';

CREATE SCHEMA IF NOT EXISTS app_private;

CREATE TABLE IF NOT EXISTS app_private.immoscout_central_credentials (
  singleton text PRIMARY KEY CHECK (singleton = 'central'),
  account_hint text NOT NULL CHECK (lower(account_hint) = 'arash@nexalabs.de'),
  ciphertext text NOT NULL,
  iv text NOT NULL,
  key_version integer NOT NULL DEFAULT 1 CHECK (key_version > 0),
  status text NOT NULL CHECK (status IN ('connected','needs_login','error')),
  enabled smallint NOT NULL DEFAULT 0 CHECK (enabled IN (0,1)),
  expires_at timestamptz,
  last_verified_at timestamptz,
  last_error text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app_private.immoscout_central_oauth_flows (
  state_hash text PRIMARY KEY,
  verifier_ciphertext text NOT NULL,
  verifier_iv text NOT NULL,
  admin_telegram_id text NOT NULL,
  user_id uuid NOT NULL,
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS immoscout_central_oauth_flows_expiry_idx
  ON app_private.immoscout_central_oauth_flows (expires_at);

CREATE TABLE IF NOT EXISTS app_private.immoscout_central_audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type text NOT NULL,
  account_hint text,
  admin_telegram_id text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS immoscout_central_audit_events_created_idx
  ON app_private.immoscout_central_audit_events (created_at DESC);

ALTER TABLE app_private.immoscout_central_credentials ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.immoscout_central_oauth_flows ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.immoscout_central_audit_events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE
  app_private.immoscout_central_credentials,
  app_private.immoscout_central_oauth_flows,
  app_private.immoscout_central_audit_events
FROM PUBLIC, anon, authenticated;

GRANT USAGE ON SCHEMA app_private TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE
  app_private.immoscout_central_credentials,
  app_private.immoscout_central_oauth_flows,
  app_private.immoscout_central_audit_events
TO service_role;
GRANT USAGE, SELECT ON SEQUENCE
  app_private.immoscout_central_audit_events_id_seq
TO service_role;

COMMENT ON TABLE app_private.immoscout_central_credentials IS
  'Encrypted central ImmoScout24 OAuth credentials used only by the housing auto-application provider adapter.';
COMMENT ON TABLE app_private.immoscout_central_oauth_flows IS
  'Short-lived, admin-authorized central ImmoScout24 OAuth and MFA flows.';
COMMENT ON TABLE app_private.immoscout_central_audit_events IS
  'Minimal audit history for central ImmoScout24 credential and auto-application state changes.';

RESET lock_timeout;
RESET statement_timeout;
