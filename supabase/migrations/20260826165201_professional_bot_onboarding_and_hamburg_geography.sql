create table if not exists public.saved_listings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.bot_users(id) on delete cascade,
  listing_id uuid not null references public.listings(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(user_id, listing_id)
);
create index if not exists saved_listings_user_created_idx on public.saved_listings(user_id, created_at desc);
create index if not exists saved_listings_listing_idx on public.saved_listings(listing_id);
alter table public.saved_listings enable row level security;
revoke all on table public.saved_listings from anon, authenticated;

