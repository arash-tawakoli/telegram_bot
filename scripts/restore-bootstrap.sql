create extension if not exists pgcrypto;
create schema if not exists app_private;

create table if not exists public.bot_users (
  id uuid primary key default gen_random_uuid(),
  telegram_user_id bigint,
  chat_id bigint,
  username text,
  first_name text,
  last_name text,
  language_code text,
  onboarding_step text,
  onboarding_state jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sources (
  id smallint primary key,
  name text not null,
  enabled boolean not null default true,
  tier text not null default 'K2',
  poll_interval_minutes integer not null default 15,
  last_checked_at timestamptz,
  consecutive_failures integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.listings (
  id uuid primary key default gen_random_uuid(),
  source_id smallint not null,
  source_listing_key text not null,
  external_id text,
  canonical_url text not null,
  title text,
  address text,
  district text,
  postal_code text,
  city text not null default 'Hamburg',
  warm_rent numeric,
  cold_rent numeric,
  rooms numeric,
  area_sqm numeric,
  available_from date,
  property_type text,
  furnished boolean,
  wbs_required boolean,
  image_url text,
  cross_source_hash text,
  raw jsonb not null default '{}'::jsonb,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  is_active boolean not null default true
);

create table if not exists public.search_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  name text,
  location text,
  max_rent numeric,
  min_rooms numeric,
  max_rooms numeric,
  min_area_sqm numeric,
  max_area_sqm numeric,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.applications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  listing_id uuid not null,
  source_id smallint not null,
  status text not null default 'pending',
  application_text text,
  attempts integer not null default 0,
  last_error text,
  submission_started_at timestamptz,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  lease_token uuid,
  lease_until timestamptz,
  next_attempt_at timestamptz not null default now(),
  wait_reason text,
  quota_local_date date,
  provider_state jsonb not null default '{}'::jsonb
);

create table if not exists public.delivery_events (
  id uuid primary key default gen_random_uuid(),
  user_id uuid,
  listing_id uuid,
  status text not null default 'pending',
  created_at timestamptz not null default now()
);

create table if not exists public.source_connectors (
  id bigint generated by default as identity primary key,
  source_id smallint not null,
  priority integer not null default 1,
  label text not null default '',
  connector_kind text not null default 'unsupported',
  enabled boolean not null default false,
  config jsonb not null default '{}'::jsonb
);

create index if not exists restore_bootstrap_sources_name_idx on public.sources(name);
